"""Show a vault's present state as a folder another program can open. Derived data, never truth.

    obsidian(vault, out)   notes in a tree of spaces, two JSON Canvas files, who.md
    notion(vault, out)     the same notes with fenced frontmatter and who.md, as a folder and a zip

The notes are a pure function of the pages committed at HEAD and who.md of the history behind
them: the same vault gives the same bytes. Each call deletes and rewrites its own folder.
Nothing reads the output back.
"""

from __future__ import annotations

import json
import re
import shutil
import zipfile
from datetime import UTC, datetime
from pathlib import Path

from conky import arch, git
from conky.errors import BadInput
from conky.page import Page, home, parse, serialize, spaces
from conky.vault import Trailer, Vault

DIST = "dist"
CANVAS = "conky.canvas"
NODE = (300, 120)
GAP = 40
COLUMNS = 3
KINDS = ("within", "watch", "ask", "writes")
OVERVIEW = "spaces.canvas"
WHO = "who.md"
ZIP = "conky.zip"
FRONT = re.compile(r"\A---\n(.*?)^---\n", re.DOTALL | re.MULTILINE)
WHO_HEAD = (
    "<!-- Generated by conky export from the vault's Git history. Do not edit: the next export "
    "rewrites this file. -->\n\n"
    "# Who signed what\n\n"
    "| page | signed by | when | kind | cause | changes |\n"
    "|---|---|---|---|---|---|\n"
)


def committed(vault: Vault) -> dict[str, Page]:
    """Return the pages committed at HEAD by name, read without the working tree."""
    if not vault._has_commits():
        return {}
    listing = git.run(["ls-tree", "-r", "--name-only", "HEAD", "pages/"], vault.path)
    found = {}
    for line in sorted(listing.splitlines()):
        if line.endswith(".md"):
            found[Path(line).stem] = parse(git.run(["show", f"HEAD:{line}"], vault.path))
    return found


def _chain(name: str, pages: dict[str, Page]) -> list[str]:
    """Return the spaces a page sits in, outermost first. A loop of spaces stops at the repeat."""
    chain: list[str] = []
    space = home(pages[name].within)
    while space in pages and space not in chain and space != name:
        chain.append(space)
        space = home(pages[space].within)
    return chain[::-1]


def _spaces(pages: dict[str, Page]) -> set[str]:
    return {s for p in pages.values() for s in spaces(p.within) if s in pages}


def _path(name: str, pages: dict[str, Page], spaces: set[str]) -> str:
    """Return where a page's note goes: a space's own note sits at the top of its folder."""
    folders = _chain(name, pages)
    if name in spaces:
        folders.append(name)
    return "/".join([*folders, f"{name}.md"])


def _note(name: str, pages: dict[str, Page]) -> str:
    """A note is the page exactly as its author wrote it: nothing is added to its body."""
    return serialize(pages[name])


def _relations(pages: dict[str, Page]) -> list[tuple[str, str, str]]:
    """Return (kind, from, to) for within, watch, ask and writes, among pages that exist."""
    found = []
    for name in sorted(pages):
        page = pages[name]
        for space in spaces(page.within):
            found.append(("within", name, space))
        for entry in (e for e in page.watch if "each" not in e):
            found.append(("watch", name, entry["on"]))
            ask = entry.get("ask")
            if isinstance(ask, dict):
                if ask.get("provider"):
                    found.append(("ask", name, ask["provider"]))
                if ask.get("writes"):
                    found.append(("writes", name, ask["writes"]))
    return [r for r in found if r[1] in pages and r[2] in pages and r[1] != r[2]]


def _block(items: list[dict]) -> tuple[int, int]:
    """Place items in rows of COLUMNS from the origin; return the width and height they fill."""
    x = y = row = width = 0
    for index, item in enumerate(items):
        if index and index % COLUMNS == 0:
            x, y, row = 0, y + row + GAP, 0
        _shift(item, x - item["x"], y - item["y"])
        x += item["width"] + GAP
        row = max(row, item["height"])
        width = max(width, x - GAP)
    return width, y + row


def _shift(item: dict, dx: int, dy: int) -> None:
    item["x"] += dx
    item["y"] += dy
    for inner in item.get("inside", []):
        _shift(inner, dx, dy)


def _flat(item: dict) -> list[dict]:
    out = [item]
    for inner in item.pop("inside", []):
        out.extend(_flat(inner))
    return out


def _layout(space: str | None, pages: dict[str, Page], spaces: set[str], seen: set[str]) -> dict:
    """Return a group for the space, holding its note, its pages and its inner spaces."""
    seen.add(space or "")
    own = [] if space is None else [space]
    members = [n for n in sorted(pages) if home(pages[n].within) == space and n != space]
    items: list[dict] = []
    for name in own + [n for n in members if n not in spaces]:
        items.append(
            {
                "id": f"page-{name}",
                "type": "file",
                "file": _path(name, pages, spaces),
                "x": 0,
                "y": 0,
                "width": NODE[0],
                "height": NODE[1],
            }
        )
    for name in (n for n in members if n in spaces and n not in seen):
        items.append(_layout(name, pages, spaces, seen))
    width, height = _block(items)
    pad = GAP if space is not None else 0
    for item in items:
        _shift(item, pad, pad)
    group = {
        "id": f"space-{space}" if space else "root",
        "type": "group",
        "x": 0,
        "y": 0,
        "width": width + 2 * pad,
        "height": height + 2 * pad,
        "inside": items,
    }
    if space:
        group["label"] = space
    return group


def _canvas(pages: dict[str, Page], spaces: set[str]) -> str:
    """Return the JSON Canvas 1.0 text: groups for spaces, file nodes, edges for relations."""
    seen: set[str] = set()
    top = _layout(None, pages, spaces, seen)
    nodes = [n for item in top["inside"] for n in _flat(item)]
    shown = {n["id"] for n in nodes}
    missing = [n for n in sorted(pages) if f"page-{n}" not in shown]
    if missing:
        base = max((n["y"] + n["height"] for n in nodes), default=-GAP) + GAP
        extra = [
            {
                "id": f"page-{n}",
                "type": "file",
                "file": _path(n, pages, spaces),
                "x": 0,
                "y": 0,
                "width": NODE[0],
                "height": NODE[1],
            }
            for n in missing
        ]
        _block(extra)
        for item in extra:
            item["y"] += base
        nodes += extra
    edges = []
    for number, (kind, source, target) in enumerate(_relations(pages)):
        edges.append(
            {
                "id": f"edge-{number}-{kind}",
                "fromNode": f"page-{source}",
                "toNode": f"page-{target}",
                "label": kind,
            }
        )
    return json.dumps({"nodes": nodes, "edges": edges}, indent=2, ensure_ascii=False) + "\n"


def _overview(space: str, pages: dict[str, Page], spaces: set[str], seen: set[str]) -> dict:
    """Return a group for the space, holding the groups of its inner spaces and a page count."""
    seen.add(space)
    inner = [
        _overview(n, pages, spaces, seen)
        for n in sorted(spaces)
        if n not in seen and home(pages[n].within) == space
    ]
    count = sum(1 for n in pages if n != space and space in _chain(n, pages))
    pad = GAP if inner else 0
    width, height = _block(inner) if inner else NODE
    for item in inner:
        _shift(item, pad, pad)
    noun = "page" if count == 1 else "pages"
    return {
        "id": f"space-{space}",
        "type": "group",
        "label": f"{space}: {count} {noun}",
        "x": 0,
        "y": 0,
        "width": width + 2 * pad,
        "height": height + 2 * pad,
        "inside": inner,
    }


def _overview_canvas(pages: dict[str, Page], spaces: set[str]) -> str:
    """Return a JSON Canvas of only the spaces, nested as they are, each with its page count."""
    seen: set[str] = set()
    tops = [n for n in sorted(spaces) if home(pages[n].within) not in spaces]
    groups = [_overview(n, pages, spaces, seen) for n in tops]
    groups += [_overview(n, pages, spaces, seen) for n in sorted(spaces) if n not in seen]
    _block(groups)
    nodes = [n for group in groups for n in _flat(group)]
    return json.dumps({"nodes": nodes, "edges": []}, indent=2, ensure_ascii=False) + "\n"


def _stamp(seconds: str) -> str:
    return datetime.fromtimestamp(int(seconds), UTC).strftime("%Y-%m-%dT%H:%M:%SZ")


def _who(vault: Vault, pages: dict[str, Page]) -> str:
    """Return who.md: a row a page, from the commits that changed it, refusals not counted."""
    last: dict[str, tuple[str, str, str, str]] = {}
    changes: dict[str, int] = {}
    if pages:
        out = git.run(["log", "--reverse", "--format=%x1e%an%x1f%at%x1f%B", "HEAD"], vault.path)
        for record in out.split("\x1e")[1:]:
            actor, stamp, message = record.split("\x1f", 2)
            found = git.trailers(message)
            page = found.get(Trailer.PAGE, "")
            kind = found.get(Trailer.KIND, "-")
            if page in pages and kind != "refused":
                cause = found.get(Trailer.CAUSE, "")[:7] or "-"
                last[page] = (actor, _stamp(stamp), kind, cause)
                changes[page] = changes.get(page, 0) + 1
    rows = []
    for name in sorted(pages):
        actor, when, kind, cause = last.get(name, ("-", "-", "-", "-"))
        rows.append(
            f"| [[{name}]] | {actor} | {when} | {kind} | {cause} | {changes.get(name, 0)} |"
        )
    return WHO_HEAD + "\n".join(rows) + ("\n" if rows else "")


def _fenced(text: str) -> str:
    """Return a note with its frontmatter turned into a fenced block at the top."""
    match = FRONT.match(text)
    if not match:
        return text
    return f"```yaml\n{match.group(1)}```\n\n{text[match.end() :]}"


def _exclude(vault: Vault, out: Path) -> None:
    """Keep the output out of the vault's tree without a tracked ignore file."""
    here = vault.path.resolve()
    try:
        rel = out.resolve().relative_to(here)
    except ValueError:
        return
    pattern = f"{DIST}/" if rel.parts[:1] == (DIST,) else f"{rel.as_posix()}/"
    exclude = here / ".git" / "info" / "exclude"
    exclude.parent.mkdir(parents=True, exist_ok=True)
    lines = exclude.read_text(encoding="utf-8").splitlines() if exclude.exists() else []
    if pattern not in lines:
        exclude.write_text("\n".join([*lines, pattern]) + "\n", encoding="utf-8")


def _clear(vault: Vault, out: Path) -> None:
    """Delete a folder an earlier export wrote, and refuse any other folder."""
    here = vault.path.resolve()
    target = out.resolve()
    if target == here or target in here.parents or (here / ".git") in (target, *target.parents):
        raise BadInput(f"{out} is the vault or holds it: give --out a folder of its own")
    if target.exists():
        if not target.is_dir() or (
            any(target.iterdir()) and not any((target / m).exists() for m in (CANVAS, WHO))
        ):
            raise BadInput(
                f"{out} exists and was not made by conky export: give --out a new folder"
            )
        shutil.rmtree(target)


@arch.part(
    "part.export.obsidian",
    "layer.edge",
    "The committed pages as an Obsidian folder of notes, two JSON Canvas files and who.md.",
    doc="connectors.md#showing-a-vault-elsewhere",
)
def obsidian(vault: Vault, out: Path | None = None) -> tuple[Path, int]:
    """Write the vault's pages as notes under out and return the folder and the page count."""
    target = out if out is not None else vault.path / DIST / "obsidian"
    pages = committed(vault)
    _clear(vault, target)
    _exclude(vault, target)
    spaces = _spaces(pages)
    for name in pages:
        note = target / _path(name, pages, spaces)
        note.parent.mkdir(parents=True, exist_ok=True)
        note.write_text(_note(name, pages), encoding="utf-8", newline="\n")
    target.mkdir(parents=True, exist_ok=True)
    for file, text in (
        (CANVAS, _canvas(pages, spaces)),
        (OVERVIEW, _overview_canvas(pages, spaces)),
        (WHO, _who(vault, pages)),
    ):
        (target / file).write_text(text, encoding="utf-8", newline="\n")
    return target, len(pages)


@arch.part(
    "part.export.notion",
    "layer.edge",
    "The committed pages as Markdown notes for Notion's import, as a folder and a zip.",
    doc="connectors.md#showing-a-vault-elsewhere",
)
def notion(vault: Vault, out: Path | None = None) -> tuple[Path, int]:
    """Write the notes with fenced frontmatter and who.md under out, and a zip of the same tree."""
    target = out if out is not None else vault.path / DIST / "notion"
    pages = committed(vault)
    _clear(vault, target)
    _exclude(vault, target)
    spaces = _spaces(pages)
    files = {_path(n, pages, spaces): _fenced(_note(n, pages)) for n in pages}
    files[WHO] = _who(vault, pages)
    for name, text in files.items():
        note = target / name
        note.parent.mkdir(parents=True, exist_ok=True)
        note.write_text(text, encoding="utf-8", newline="\n")
    target.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(target / ZIP, "w", zipfile.ZIP_DEFLATED) as archive:
        for name in sorted(files):
            info = zipfile.ZipInfo(f"conky/{name}", (1980, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            archive.writestr(info, files[name].encode("utf-8"))
    return target, len(pages)
